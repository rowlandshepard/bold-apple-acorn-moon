function seal(drafts: Draft[]): Card[] {
  return drafts.map((draft, index) => {
    const slot = (index % 4) as 0 | 1 | 2 | 3;
    const choices = [...draft.wrong];
    choices.splice(slot, 0, draft.correct);
    return {
      id: `l${draft.lecture}-${String(index + 1).padStart(3, "0")}`,
      lecture: draft.lecture,
      topic: draft.topic,
      prompt: draft.prompt,
      choices: choices as [string, string, string, string],
      answer: slot,
      why: draft.why,
    };
  });
}

export const CARDS: Card[] = seal(DRAFTS);

const seen = new Set<string>();
for (const card of CARDS) {
  if (seen.has(card.id)) throw new Error(`Duplicate card id ${card.id}`);
  seen.add(card.id);
  if (new Set(card.choices).size !== 4) {
    throw new Error(`Card ${card.id} has duplicate choices`);
  }
}
